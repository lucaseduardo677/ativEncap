package main;

public class Pessoa {
    private String nome;
    private int idade;
    private String pais;

    public String getNome() {
        return nome;
    }

    public void setNome(String n) {
        nome = n;
    }

    public int getIdade() {
        return idade;
    }

    public void setIdade(int i) {
        idade = i;
    }

    public String getPais() {
        return pais;
    }

    public void setPais(String p) {
        pais = p;
    }
}